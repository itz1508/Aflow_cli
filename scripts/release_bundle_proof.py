"""Release-evidence portability proof.

Validates that release-evidence/ is a portable, sanitized bundle safe to ship:

  1. Scans every evidence file for host-specific tokens (repository path,
     home directory, and username in both slash orientations). A portable
     bundle must contain none.
  2. Generates release-evidence/evidence-inventory.json - every file with its
     sha256, byte size, and a short description.
  3. Generates release-evidence/sanitization-report.json - the exact tokens
     scanned for and the per-file leak count (all zero when clean).

The two generated files are themselves included in the inventory (their
sha256 is recomputed after writing so the manifest stays self-consistent).

Sanitized summary is printed; exit 0 only when the bundle is leak-free.

Run: uv run python scripts/release_bundle_proof.py
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BUNDLE = REPO_ROOT / "release-evidence"
INVENTORY = BUNDLE / "evidence-inventory.json"
SANITIZATION = BUNDLE / "sanitization-report.json"

# Files that are (re)generated by this script; excluded from the pre-write scan.
GENERATED = {INVENTORY, SANITIZATION}

DESCRIPTIONS = {
    "release-proof.json": "Top-level acceptance summary and proof index.",
    "MARKETING_PROOF.md": "Human-readable acceptance claims.",
    "mcp-proof/round-trip.json": "Real MCP stdio round trip + unknown-property rejection.",
    "verification-operation/transaction-proof/proof.json": "Transaction / concurrency proof.",
    "semantic-operation/continuation-proof/proof.json": "Semantic truncation / continuation proof.",
    "semantic-operation/gap-records.json": "Semantic gap records (unresolved observations).",
    "semantic-operation/semantic-provenance.json": "Semantic provenance record.",
    "semantic-operation/unresolved-decisions.json": "Unresolved decision observations.",
    "semantic-operation/unresolved-info.json": "Unresolved information observations.",
    "continuity-proof/full-lifecycle/proof.json": "Full review->verify->resume lifecycle proof.",
    "continuity-proof/stale-revalidation/proof.json": "Stale revalidation proof.",
    "continuity-proof/continuation-package.json": "Continuation package snapshot.",
    "continuity-proof/updated-plan.json": "Derived step plan snapshot.",
    "continuity-proof/work-status.json": "Work-status snapshot.",
    "summary-proof/public-summaries.json": "Public-summary integrity proof.",
    "clean-install/proof.json": "Clean non-editable install command battery.",
    "clean-install-proof/result.txt": "Clean-install narrative note.",
    "test-proof/full-suite.txt": "Deterministic suite result note.",
}


def _tokens() -> dict[str, str]:
    tokens: dict[str, str] = {}
    repo = str(REPO_ROOT)
    tokens[repo] = "<REPO_ROOT>"
    tokens[repo.replace("\\", "/")] = "<REPO_ROOT>"
    home = os.environ.get("USERPROFILE") or os.environ.get("HOME")
    if home:
        tokens[str(Path(home))] = "<HOME>"
        tokens[str(Path(home)).replace("\\", "/")] = "<HOME>"
    user = os.environ.get("USERNAME") or os.environ.get("USER")
    if user:
        tokens[user] = "<USER>"
    # Drop empties / duplicates that collapse to nothing.
    return {k: v for k, v in tokens.items() if k}


def _iter_files():
    for path in sorted(BUNDLE.rglob("*")):
        if path.is_file():
            yield path


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _rel(path: Path) -> str:
    return path.relative_to(BUNDLE).as_posix()


def main() -> int:
    tokens = _tokens()

    # --- 1. Leak scan over every non-generated file ---
    def scan_file(path: Path) -> dict[str, int]:
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            return {}
        # Report leaks by placeholder category, never by echoing the raw token,
        # so this report can itself be shipped without reintroducing a leak.
        hits: dict[str, int] = {}
        for needle, placeholder in tokens.items():
            count = text.count(needle)
            if count:
                hits[placeholder] = hits.get(placeholder, 0) + count
        return hits

    per_file_leaks: dict[str, dict[str, int]] = {}
    for path in _iter_files():
        if path in GENERATED:
            continue
        per_file_leaks[_rel(path)] = scan_file(path)

    leaked = {rel: hits for rel, hits in per_file_leaks.items() if any(v for v in hits.values())}

    sanitization = {
        "proof_type": "release-evidence-portability",
        "token_categories_scanned": sorted(set(tokens.values())),
        "token_replacements": {"<REPO_ROOT>": "repository path", "<HOME>": "home directory", "<USER>": "username"},
        "note": "Leaks are reported by placeholder category only; the report never echoes the raw host token.",
        "files_scanned": len(per_file_leaks),
        "files_with_leaks": sorted(leaked.keys()),
        "leak_details": leaked,
        "bundle_is_portable": not leaked,
    }
    tmp = SANITIZATION.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(sanitization, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, SANITIZATION)

    # --- 2. Inventory (after sanitization report exists so it is included).
    # The inventory cannot hash itself, so it lists every file except itself.
    entries = []
    for path in _iter_files():
        if path == INVENTORY:
            continue
        rel = _rel(path)
        entries.append({
            "path": rel,
            "sha256": _sha256(path),
            "size_bytes": path.stat().st_size,
            "description": DESCRIPTIONS.get(rel, "Generated portability artifact." if path in GENERATED else "Evidence artifact."),
        })
    inventory = {
        "proof_type": "release-evidence-inventory",
        "bundle_root": "release-evidence",
        "note": "Lists every bundle file except evidence-inventory.json itself (a manifest cannot hash itself).",
        "file_count": len(entries),
        "files": entries,
    }
    tmp = INVENTORY.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(inventory, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, INVENTORY)

    inventoried = {e["path"] for e in entries} | {_rel(INVENTORY)}
    all_files = {_rel(p) for p in _iter_files()}

    # Final full re-scan INCLUDING the two generated files, so the manifest and
    # sanitization report are themselves proven leak-free.
    generated_leaks = {_rel(p): scan_file(p) for p in (SANITIZATION, INVENTORY)}
    generated_leaked = {rel: hits for rel, hits in generated_leaks.items() if any(v for v in hits.values())}

    checks = {
        "bundle_is_portable": not leaked,
        "generated_files_leak_free": not generated_leaked,
        "inventory_written": INVENTORY.exists(),
        "sanitization_report_written": SANITIZATION.exists(),
        "every_file_inventoried": inventoried == all_files,
    }
    result = {
        "all_checks_passed": all(checks.values()),
        "checks": checks,
        "files_scanned": len(per_file_leaks) + len(generated_leaks),
        "files_with_leaks": sorted(list(leaked.keys()) + list(generated_leaked.keys())),
        "file_count": len(entries) + 1,
    }
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result["all_checks_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
